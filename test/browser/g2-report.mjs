#!/usr/bin/env node
// Render ACTIONS.md for a G2 evidence directory from its actions.json,
// coverage.json and build-gates.json. Pure formatting: every value comes from
// those files, which come from records.jsonl / spans.jsonl.
import fs from 'node:fs';
import path from 'node:path';

const dir = path.resolve(process.argv[2]);
const actions = JSON.parse(fs.readFileSync(path.join(dir, 'actions.json'), 'utf8'));
const cell = value => String(value ?? '').replace(/\|/gu, '\\|').replace(/\n/gu, ' ');
const target = action => {
  const attrs = action.target?.attributes || {};
  const bits = ['aria-label', 'name', 'id', 'type', 'role'].filter(key => attrs[key]).map(key => `${key}=${attrs[key]}`);
  return `${action.event} on <${action.target?.tag || '?'}${bits.length ? ` ${bits.join(' ')}` : ''}>`;
};
const entry = action => action.entry
  ? `\`${action.entry.file}:${action.entry.line}\` (span ${action.entry.start}-${action.entry.end}, ${action.entry.rooted ? 'rooted' : 'unrooted'}, invoked_by=${action.entry.invoked_by}) \`${cell(action.entry.snippet).slice(0, 140)}\``
  : action.abstention
    ? `abstained: stopped_at entry_handler, ${String(action.abstention.because || 'no element-bound handler observed in instrumented code (uninstrumented and third-party handlers are not seen)').replace(/; global listeners: \[.*$/u, '')}; global listeners ran: ${action.abstention.global_listeners.map(item => `\`${item}\``).join(', ') || 'none'}${action.abstention.library_bound ? `; library-bound: ${JSON.stringify(action.abstention.library_bound)}` : ''}`
    : `none: ${action.entry_frontier}`;
const requestSummary = action => {
  if (!action.requests.length) return '';
  const writes = action.requests.filter(request => request.method !== 'GET');
  const reads = action.requests.length - writes.length;
  const parts = writes.map(request => `${request.method} ${request.path}`);
  if (reads) parts.push(`${reads} GET`);
  return parts.join('; ');
};
const backendSummary = action => {
  const requests = action.requests.filter(request => request.method !== 'GET');
  const list = requests.length ? requests : action.requests.slice(0, 1);
  return list.map(request => {
    const route = request.route ? `route ${request.route.method || ''} ${request.route.route} → ${request.route.status}` : null;
    const handler = request.handlers?.length ? `handler span #${request.handlers.at(-1).index} (${request.handlers.at(-1).name})` : null;
    const db = request.db?.length ? `db ${request.db.map(row => `${row.operation} ${row.collection}`).join(', ')}` : null;
    const reached = [route, handler, db].filter(Boolean).join(' → ') || 'network';
    return `${reached}${request.stopped_at ? `; stopped at ${request.stopped_at} because ${request.because}` : ''}`;
  }).join('<br>');
};
const lines = [`# Per-action table (${path.basename(dir)})`, '',
  'Generated by `test/browser/g2-report.mjs` from `actions.json` (itself computed from `records.jsonl`, `spans.jsonl` and the attribution manifest by package code: `indexEntryHandlerUnits`, `attachBackendSpans`).',
  'Keystroke/focus/input rows with no credited function and no request are counted but not listed. Identical consecutive rows are collapsed (×N).', ''];
for (const step of actions) {
  lines.push(`## Step ${step.step}: ${step.name} (${step.status}${step.error ? `: ${cell(step.error)}` : ''})`, '', `Scripted user action: ${step.description}.`, '');
  const listed = step.actions.filter(action => action.entry || action.requests.length || !['keydown', 'focusin', 'input', 'change'].includes(action.event));
  const omitted = step.actions.length - listed.length;
  lines.push('| dom.action | credited entry handler (file:line, span, source) | requests | backend: reached / stopped at / because |', '|---|---|---|---|');
  let previous = null; let repeat = 0;
  const flush = () => { if (previous) lines.push(`| ${cell(previous[0])}${repeat > 1 ? ` ×${repeat}` : ''} | ${previous[1]} | ${cell(previous[2])} | ${cell(previous[3])} |`); };
  for (const action of listed) {
    const row = [target(action), entry(action), requestSummary(action), backendSummary(action)];
    if (previous && JSON.stringify(previous) === JSON.stringify(row)) { repeat += 1; continue; }
    flush(); previous = row; repeat = 1;
  }
  flush();
  lines.push('', `${step.actions.length} dom.action rows in this step; ${omitted} keystroke/focus/input rows without a credited function or request not listed.`, '');
}
// Frontier counts by reason (every dom.action row, and every attributed request).
const all = actions.flatMap(step => step.actions);
const records = fs.readFileSync(path.join(dir, 'records.jsonl'), 'utf8').trim().split('\n').map(line => JSON.parse(line));
const unattributed = records.filter(row => row.kind === 'network.request' && !row.internal && !/\/__capture|\/__producttrace\//u.test(String(row.url || '')) && !row.action_id);
const count = list => Object.fromEntries(Object.entries(Object.groupBy(list, value => value)).map(([key, values]) => [key, values.length]));
const summary = {
  steps: actions.length, steps_done: actions.filter(step => step.status === 'done').length,
  dom_actions: all.length, by_event: count(all.map(action => action.event)),
  credited: all.filter(action => action.entry).length,
  credited_rooted: all.filter(action => action.entry?.rooted).length,
  distinct_credited_functions: new Set(all.filter(action => action.entry).map(action => action.entry.function_id)).size,
  entry_frontiers: count(all.filter(action => !action.entry).map(action => action.abstention ? `stopped_at entry_handler: ${String(action.abstention.because || 'no element-bound handler observed in instrumented code (uninstrumented and third-party handlers are not seen)').replace(/; global listeners: \[.*$/u, '')}` : action.entry_frontier)),
  abstained_at_entry_handler: all.filter(action => action.abstention).length,
  actions_with_element_key: all.filter(action => action.element_key).length,
  attributed_requests: all.reduce((n, action) => n + action.requests.length, 0),
  request_stops: count(all.flatMap(action => action.requests.map(request => request.stopped_at ? `stopped at ${request.stopped_at}: ${request.because}` : `reached ${request.reached}`))),
  unattributed_requests: unattributed.length,
  unattributed_request_paths: unattributed.map(row => `${row.method} ${new URL(row.url, 'http://origin').pathname}`),
};
fs.writeFileSync(path.join(dir, 'summary.json'), `${JSON.stringify(summary, null, 2)}\n`);
lines.splice(4, 0, '## Summary', '', '```json', JSON.stringify(summary, null, 2), '```', '');
fs.writeFileSync(path.join(dir, 'ACTIONS.md'), `${lines.join('\n')}\n`);
console.log(path.join(dir, 'ACTIONS.md'));
